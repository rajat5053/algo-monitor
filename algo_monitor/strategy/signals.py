"""
Trading signal generation based on support/resistance zones.

Implements the six setup types:
1. Bounce from support   — price touches support zone and bounces up
2. Rejection from resistance — price touches resistance zone and rejects down
3. Breakout above resistance — price closes above resistance zone
4. Breakdown below support   — price closes below support zone
5. Retest after breakout/breakdown — price returns to the broken level
6. Approaching zone          — early warning when price nears a key zone

All signals require completed candle confirmation by default.
Each signal has explicit, testable conditions and an expiry mechanism.
"""

from __future__ import annotations

import hashlib
from dataclasses import dataclass, field
from datetime import datetime, timezone
from enum import Enum
from typing import TYPE_CHECKING

from algo_monitor.data.models import Candle
from algo_monitor.strategy.levels import Zone, ZoneType
from algo_monitor.utils.logging import get_logger

if TYPE_CHECKING:
    from algo_monitor.config.settings import StrategyConfig

logger = get_logger("strategy.signals")


class SetupType(str, Enum):
    BOUNCE_SUPPORT = "bounce_support"
    REJECTION_RESISTANCE = "rejection_resistance"
    BREAKOUT_RESISTANCE = "breakout_resistance"
    BREAKDOWN_SUPPORT = "breakdown_support"
    RETEST_BREAKOUT = "retest_breakout"
    RETEST_BREAKDOWN = "retest_breakdown"
    APPROACHING_ZONE = "approaching_zone"
    HEAD_AND_SHOULDERS = "head_and_shoulders"
    FIRSTY_CONTINUATION = "firsty_continuation"


class Direction(str, Enum):
    LONG = "long"
    SHORT = "short"
    BUY = "long"
    SELL = "short"


@dataclass
class Signal:
    """A trading signal generated by the strategy engine."""

    symbol: str
    exchange: str
    setup_type: SetupType
    direction: Direction
    timeframe: str                  # e.g. '5m' (confirmation timeframe)
    zone: Zone | None = None        # The relevant S/R zone

    # Price references (may be None if computation is impossible)
    entry_ref: float | None = None
    stop_loss: float | None = None
    target: float | None = None
    risk_reward: float | None = None

    strength: float = 0.5           # 0-1 composite score
    reason: str = ""                # Human-readable explanation
    invalidation: str = ""          # What would cancel this signal

    strategy_module: str = "core_sr" # 'core_sr', 'head_and_shoulders', 'firsty_continuation'
    metadata: dict = field(default_factory=dict)

    created_at: datetime = field(default_factory=lambda: datetime.now(timezone.utc))
    expires_at: datetime | None = None
    is_active: bool = True

    @property
    def entry_price(self) -> float | None:
        return self.entry_ref

    @property
    def target_price(self) -> float | None:
        return self.target

    @property
    def reward_risk_ratio(self) -> float | None:
        return self.risk_reward

    @property
    def confidence(self) -> float:
        return self.strength

    @property
    def signal_id(self) -> str:
        """Deterministic ID for deduplication."""
        raw = f"{self.symbol}|{self.exchange}|{self.setup_type.value}|{self.direction.value}"
        if self.zone:
            raw += f"|{self.zone.mid_price:.2f}"
        if self.strategy_module != "core_sr":
            raw += f"|{self.strategy_module}"
        return hashlib.md5(raw.encode()).hexdigest()[:12]

    def is_expired(self, now: datetime | None = None) -> bool:
        if self.expires_at is None:
            return False
        now = now or datetime.now(timezone.utc)
        return now >= self.expires_at


class SignalGenerator:
    """
    Generates trading signals from price data and S/R zones.

    The generator checks all six setup types against the latest
    completed candles and active zones.  It deduplicates signals
    to avoid spamming the same setup repeatedly.

    Target calculation:
      - In 'adaptive' mode (default): uses AdaptiveTargetPlanner to place
        the target just before the nearest opposing S/R zone. Falls back to
        fixed_rr if no suitable zone is found.
      - In 'fixed_rr' mode: entry ± risk × target_fixed_rr_multiple.
      min_reward_risk is ONLY used as a validation floor in the risk manager.
    """

    def __init__(self, config: StrategyConfig):
        self.config = config
        self._recent_signal_ids: set[str] = set()

    def generate_signals(
        self,
        symbol: str,
        exchange: str,
        candles: list[Candle],
        zones: list[Zone],
        htf_zones: list[Zone] | None = None,
    ) -> list[Signal]:
        """
        Generate signals from the latest candle data and zones.

        Args:
            symbol: Instrument symbol
            exchange: Exchange name
            candles: Recent LTF (5m) candles, chronological order
            zones: LTF zones (or HTF zones if no separate list)
            htf_zones: Optional separate higher-timeframe zones for context
        """
        if len(candles) < 3:
            return []

        # Use HTF zones for S/R if provided, otherwise use the zones passed
        sr_zones = htf_zones if htf_zones else zones
        all_zones = list(sr_zones)
        seen_ids = {id(z) for z in sr_zones}
        for z in zones:
            if id(z) not in seen_ids:
                all_zones.append(z)
                seen_ids.add(id(z))


        if not sr_zones:
            return []

        signals: list[Signal] = []
        timeframe = candles[0].interval if candles else "5m"

        # Only use completed candles for confirmation
        completed = [c for c in candles if c.is_complete]
        if len(completed) < 2:
            return []

        current = completed[-1]
        prev = completed[-2]

        for zone in sr_zones:
            if not zone.strength:
                continue

            # 1. Bounce from support
            sig = self._check_bounce_support(
                symbol, exchange, timeframe, current, prev, zone, all_zones
            )
            if sig:
                signals.append(sig)

            # 2. Rejection from resistance
            sig = self._check_rejection_resistance(
                symbol, exchange, timeframe, current, prev, zone, all_zones
            )
            if sig:
                signals.append(sig)

            # 3. Breakout above resistance
            sig = self._check_breakout_resistance(
                symbol, exchange, timeframe, current, prev, zone, all_zones
            )
            if sig:
                signals.append(sig)

            # 4. Breakdown below support
            sig = self._check_breakdown_support(
                symbol, exchange, timeframe, current, prev, zone, all_zones
            )
            if sig:
                signals.append(sig)

            # 5. Retest checks
            sig = self._check_retest(
                symbol, exchange, timeframe, current, prev, zone, completed, all_zones
            )
            if sig:
                signals.append(sig)

            # 6. Approaching zone (early warning — informational, does NOT create positions)
            sig = self._check_approaching(
                symbol, exchange, timeframe, current, zone
            )
            if sig:
                signals.append(sig)

        # -------------------------------------------------------------
        # Modular Strategy Extensions (Document 2)
        # -------------------------------------------------------------
        if getattr(self.config, "head_and_shoulders", None) and self.config.head_and_shoulders.enabled:
            try:
                from algo_monitor.strategy.head_and_shoulders import HeadAndShouldersDetector
                hs_detector = HeadAndShouldersDetector(self.config)
                hs_signals = hs_detector.detect_signals(
                    symbol=symbol,
                    exchange=exchange,
                    candles=completed,
                    zones=all_zones,
                    timeframe=timeframe,
                )
                signals.extend(hs_signals)
            except Exception as exc:
                logger.error("Error in HeadAndShouldersDetector: %s", exc)

        if getattr(self.config, "firsty_continuation", None) and self.config.firsty_continuation.enabled:
            try:
                from algo_monitor.strategy.trend_continuation import FirstyContinuationDetector
                tc_detector = FirstyContinuationDetector(self.config)
                tc_signals = tc_detector.detect_signals(
                    symbol=symbol,
                    exchange=exchange,
                    candles=completed,
                    zones=all_zones,
                    timeframe=timeframe,
                )
                signals.extend(tc_signals)
            except Exception as exc:
                logger.error("Error in FirstyContinuationDetector: %s", exc)

        # Deduplicate
        unique = []
        for sig in signals:
            if sig.signal_id not in self._recent_signal_ids:
                self._recent_signal_ids.add(sig.signal_id)
                unique.append(sig)

        # Prune old signal IDs to prevent unbounded growth
        if len(self._recent_signal_ids) > 500:
            self._recent_signal_ids = set(
                list(self._recent_signal_ids)[-250:]
            )

        if unique:
            logger.info(
                "Generated %d new signals for %s/%s", len(unique), symbol, exchange
            )

        return unique

    # --- Target computation (P0-E fix) ---

    def _compute_target(
        self,
        entry: float,
        stop: float,
        direction: str,
        zone: Zone,
        all_zones: list[Zone],
    ) -> tuple[float, str]:
        """
        Compute the trade target price and a short description of how it was set.

        In 'adaptive' mode:
          - Identifies the nearest opposing zone in the trade direction.
          - Places the target just before that zone (minus zone_clearance_buffer_pct).
          - Falls back to fixed_rr if no opposing zone is found within a usable distance.

        In 'fixed_rr' mode:
          - target = entry ± risk × target_fixed_rr_multiple.

        Returns:
            (target_price, target_description)
        """
        risk = abs(entry - stop)
        rr_multiple = getattr(self.config, "target_fixed_rr_multiple", 1.5)
        mode = getattr(self.config, "target_mode", "fixed_rr")
        buffer_pct = getattr(self.config, "zone_clearance_buffer_pct", 0.2)

        if mode == "adaptive" and all_zones:
            try:
                from algo_monitor.strategy.adaptive_target import AdaptiveTargetPlanner
                planner = AdaptiveTargetPlanner(self.config)
                result = planner.compute_initial_target(
                    entry=entry,
                    stop=stop,
                    direction=direction,
                    all_zones=all_zones,
                    source_zone=zone,
                )
                if result.target is not None:
                    return result.target, result.method
            except Exception as exc:
                logger.warning(
                    "AdaptiveTargetPlanner failed (%s); falling back to fixed_rr", exc
                )

        # Fixed R:R fallback
        if direction == "long":
            target = entry + risk * rr_multiple
        else:
            target = entry - risk * rr_multiple
        return target, f"fixed_rr ({rr_multiple}R fallback)"

    def _check_bounce_support(
        self,
        symbol: str,
        exchange: str,
        tf: str,
        current: Candle,
        prev: Candle,
        zone: Zone,
        all_zones: list[Zone] | None = None,
    ) -> Signal | None:
        """
        Bounce from support:
        - Previous candle's low touched or entered the support zone
        - Current candle closes ABOVE the support zone (bounce confirmed)
        - Current candle is bullish
        """
        if zone.zone_type != ZoneType.SUPPORT or getattr(zone, "is_broken", False):
            return None

        # Prev candle low entered the zone
        prev_touched = prev.low <= zone.price_high and prev.low >= zone.price_low * 0.995

        # Current candle bounced — closed above zone and is bullish
        bounced = current.close > zone.price_high and current.is_bullish

        if not (prev_touched and bounced):
            return None

        entry = current.close
        stop = zone.price_low * 0.995  # Just below zone
        risk = entry - stop
        if risk <= 0:
            return None

        target, target_method = self._compute_target(
            entry, stop, "long", zone, all_zones or []
        )
        rr = (target - entry) / risk if risk > 0 else 0

        return Signal(
            symbol=symbol,
            exchange=exchange,
            setup_type=SetupType.BOUNCE_SUPPORT,
            direction=Direction.LONG,
            timeframe=tf,
            zone=zone,
            entry_ref=entry,
            stop_loss=stop,
            target=target,
            risk_reward=rr,
            strength=zone.strength * 0.8,
            reason=(
                f"Price bounced from support zone "
                f"[{zone.price_low:.2f} - {zone.price_high:.2f}] "
                f"({zone.touches} touches, strength={zone.strength:.2f}). "
                f"Prev candle low {prev.low:.2f} entered zone, "
                f"current candle closed bullish at {current.close:.2f}. "
                f"Target method: {target_method}."
            ),
            invalidation=(
                f"Close below {stop:.2f} invalidates this setup. "
                f"Zone breakdown would flip support to potential resistance."
            ),
        )

    def _check_rejection_resistance(
        self,
        symbol: str,
        exchange: str,
        tf: str,
        current: Candle,
        prev: Candle,
        zone: Zone,
        all_zones: list[Zone] | None = None,
    ) -> Signal | None:
        """
        Rejection from resistance:
        - Previous candle's high touched or entered the resistance zone
        - Current candle closes BELOW the resistance zone (rejection confirmed)
        - Current candle is bearish
        """
        if zone.zone_type != ZoneType.RESISTANCE or getattr(zone, "is_broken", False):
            return None

        prev_touched = prev.high >= zone.price_low and prev.high <= zone.price_high * 1.005
        rejected = current.close < zone.price_low and current.is_bearish

        if not (prev_touched and rejected):
            return None

        entry = current.close
        stop = zone.price_high * 1.005
        risk = stop - entry
        if risk <= 0:
            return None

        target, target_method = self._compute_target(
            entry, stop, "short", zone, all_zones or []
        )
        rr = (entry - target) / risk if risk > 0 else 0

        return Signal(
            symbol=symbol,
            exchange=exchange,
            setup_type=SetupType.REJECTION_RESISTANCE,
            direction=Direction.SHORT,
            timeframe=tf,
            zone=zone,
            entry_ref=entry,
            stop_loss=stop,
            target=target,
            risk_reward=rr,
            strength=zone.strength * 0.8,
            reason=(
                f"Price rejected from resistance zone "
                f"[{zone.price_low:.2f} - {zone.price_high:.2f}] "
                f"({zone.touches} touches, strength={zone.strength:.2f}). "
                f"Prev candle high {prev.high:.2f} entered zone, "
                f"current candle closed bearish at {current.close:.2f}. "
                f"Target method: {target_method}."
            ),
            invalidation=(
                f"Close above {stop:.2f} invalidates this setup. "
                f"Resistance breakout would flip to potential support."
            ),
        )

    def _check_breakout_resistance(
        self,
        symbol: str,
        exchange: str,
        tf: str,
        current: Candle,
        prev: Candle,
        zone: Zone,
        all_zones: list[Zone] | None = None,
    ) -> Signal | None:
        """
        Breakout above resistance:
        - Previous candle closed below resistance zone
        - Current candle closes ABOVE zone by at least breakout_threshold_pct
        - Confirmation via a strong bullish candle
        """
        if zone.zone_type != ZoneType.RESISTANCE:
            return None

        threshold = zone.price_high * (1 + self.config.breakout_threshold_pct / 100)
        prev_below = prev.close < zone.price_high
        current_above = current.close >= threshold

        if not (prev_below and current_above):
            return None

        # Require a reasonably strong candle (body > 40% of range)
        if current.range_size > 0 and current.body_size / current.range_size < 0.4:
            return None

        entry = current.close
        stop = zone.price_low * 0.998
        risk = entry - stop
        if risk <= 0:
            return None

        target, target_method = self._compute_target(
            entry, stop, "long", zone, all_zones or []
        )
        rr = (target - entry) / risk if risk > 0 else 0

        return Signal(
            symbol=symbol,
            exchange=exchange,
            setup_type=SetupType.BREAKOUT_RESISTANCE,
            direction=Direction.LONG,
            timeframe=tf,
            zone=zone,
            entry_ref=entry,
            stop_loss=stop,
            target=target,
            risk_reward=rr,
            strength=zone.strength * 0.7,
            reason=(
                f"Breakout above resistance zone "
                f"[{zone.price_low:.2f} - {zone.price_high:.2f}]. "
                f"Closed at {current.close:.2f}, above threshold {threshold:.2f}. "
                f"Previous close was {prev.close:.2f} (below zone). "
                f"Target method: {target_method}."
            ),
            invalidation=(
                f"Close back below {zone.price_high:.2f} would be a failed breakout. "
                f"Stop below zone at {stop:.2f}."
            ),
        )

    def _check_breakdown_support(
        self,
        symbol: str,
        exchange: str,
        tf: str,
        current: Candle,
        prev: Candle,
        zone: Zone,
        all_zones: list[Zone] | None = None,
    ) -> Signal | None:
        """
        Breakdown below support:
        - Previous candle closed above support zone
        - Current candle closes BELOW zone by at least breakout_threshold_pct
        """
        if zone.zone_type != ZoneType.SUPPORT:
            return None

        threshold = zone.price_low * (1 - self.config.breakout_threshold_pct / 100)
        prev_above = prev.close > zone.price_low
        current_below = current.close <= threshold

        if not (prev_above and current_below):
            return None

        if current.range_size > 0 and current.body_size / current.range_size < 0.4:
            return None

        entry = current.close
        stop = zone.price_high * 1.002
        risk = stop - entry
        if risk <= 0:
            return None

        target, target_method = self._compute_target(
            entry, stop, "short", zone, all_zones or []
        )
        rr = (entry - target) / risk if risk > 0 else 0

        return Signal(
            symbol=symbol,
            exchange=exchange,
            setup_type=SetupType.BREAKDOWN_SUPPORT,
            direction=Direction.SHORT,
            timeframe=tf,
            zone=zone,
            entry_ref=entry,
            stop_loss=stop,
            target=target,
            risk_reward=rr,
            strength=zone.strength * 0.7,
            reason=(
                f"Breakdown below support zone "
                f"[{zone.price_low:.2f} - {zone.price_high:.2f}]. "
                f"Closed at {current.close:.2f}, below threshold {threshold:.2f}. "
                f"Target method: {target_method}."
            ),
            invalidation=(
                f"Close back above {zone.price_low:.2f} would be a failed breakdown. "
                f"Stop above zone at {stop:.2f}."
            ),
        )

    def _check_retest(
        self,
        symbol: str,
        exchange: str,
        tf: str,
        current: Candle,
        prev: Candle,
        zone: Zone,
        candles: list[Candle],
        all_zones: list[Zone] | None = None,
    ) -> Signal | None:
        """
        Retest after breakout/breakdown:
        - Price previously broke through the zone (look back N candles)
        - Price has now returned to the zone level
        - Showing signs of the zone holding as new support/resistance
        """
        if len(candles) < 10:
            return None

        lookback = min(20, len(candles) - 2)
        recent_candles = candles[-(lookback + 2):-2]  # Exclude current and prev

        if zone.zone_type == ZoneType.RESISTANCE:
            # Was there a breakout? (candles closing above zone)
            broke_above = any(
                c.close > zone.price_high * 1.002 for c in recent_candles
            )
            if not broke_above:
                return None

            # Is price retesting the zone from above?
            retest_tol = zone.mid_price * self.config.retest_tolerance_pct / 100
            retesting = (
                abs(current.low - zone.price_high) <= retest_tol
                and current.close > zone.price_high
                and current.is_bullish
            )
            if not retesting:
                return None

            entry = current.close
            stop = zone.price_low * 0.998
            risk = entry - stop
            if risk <= 0:
                return None

            target, target_method = self._compute_target(
                entry, stop, "long", zone, all_zones or []
            )

            return Signal(
                symbol=symbol,
                exchange=exchange,
                setup_type=SetupType.RETEST_BREAKOUT,
                direction=Direction.LONG,
                timeframe=tf,
                zone=zone,
                entry_ref=entry,
                stop_loss=stop,
                target=target,
                risk_reward=(target - entry) / risk,
                strength=zone.strength * 0.9,
                reason=(
                    f"Retest of broken resistance (now support) "
                    f"[{zone.price_low:.2f} - {zone.price_high:.2f}]. "
                    f"Zone held as new support with bullish close at {current.close:.2f}. "
                    f"Target method: {target_method}."
                ),
                invalidation=f"Close below {stop:.2f} invalidates the retest.",
            )

        elif zone.zone_type == ZoneType.SUPPORT:
            broke_below = any(
                c.close < zone.price_low * 0.998 for c in recent_candles
            )
            if not broke_below:
                return None

            retest_tol = zone.mid_price * self.config.retest_tolerance_pct / 100
            retesting = (
                abs(current.high - zone.price_low) <= retest_tol
                and current.close < zone.price_low
                and current.is_bearish
            )
            if not retesting:
                return None

            entry = current.close
            stop = zone.price_high * 1.002
            risk = stop - entry
            if risk <= 0:
                return None

            target, target_method = self._compute_target(
                entry, stop, "short", zone, all_zones or []
            )

            return Signal(
                symbol=symbol,
                exchange=exchange,
                setup_type=SetupType.RETEST_BREAKDOWN,
                direction=Direction.SHORT,
                timeframe=tf,
                zone=zone,
                entry_ref=entry,
                stop_loss=stop,
                target=target,
                risk_reward=(entry - target) / risk,
                strength=zone.strength * 0.9,
                reason=(
                    f"Retest of broken support (now resistance) "
                    f"[{zone.price_low:.2f} - {zone.price_high:.2f}]. "
                    f"Zone held as new resistance with bearish close at {current.close:.2f}. "
                    f"Target method: {target_method}."
                ),
                invalidation=f"Close above {stop:.2f} invalidates the retest.",
            )

        return None

    def _check_approaching(
        self,
        symbol: str,
        exchange: str,
        tf: str,
        current: Candle,
        zone: Zone,
    ) -> Signal | None:
        """
        Early warning: price approaching an important zone.
        This is informational, not a trade signal.
        """
        if getattr(zone, "is_broken", False):
            return None

        dist = zone.distance_pct(current.close)

        if dist <= 0 or dist > self.config.approach_distance_pct:
            return None

        # Only warn for stronger zones
        if zone.strength < 0.4:
            return None

        direction = (
            Direction.LONG
            if zone.zone_type == ZoneType.SUPPORT
            else Direction.SHORT
        )

        return Signal(
            symbol=symbol,
            exchange=exchange,
            setup_type=SetupType.APPROACHING_ZONE,
            direction=direction,
            timeframe=tf,
            zone=zone,
            entry_ref=None,
            stop_loss=None,
            target=None,
            strength=zone.strength * 0.3,  # Lower strength — just a warning
            reason=(
                f"Price ({current.close:.2f}) approaching "
                f"{zone.zone_type.value} zone "
                f"[{zone.price_low:.2f} - {zone.price_high:.2f}] "
                f"(distance: {dist:.2f}%, strength: {zone.strength:.2f}). "
                f"Watch for reaction."
            ),
            invalidation="Informational alert; no trade conditions defined.",
        )
